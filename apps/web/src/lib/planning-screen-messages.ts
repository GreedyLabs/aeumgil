const languageIndex: Record<Exclude<Lang, "ko">, number> = {
  en: 0,
  "zh-CN": 1,
  "zh-TW": 2,
  ja: 3,
  de: 4,
  fr: 5,
};
export function planningScreenMessage(text: string, lang: Lang): string | undefined {
  if (lang === "ko") return undefined;
  const index = languageIndex[lang];
  const key = text.trim().replace(/\s+/g, " ");
  const exact = PLANNING_SCREEN_MESSAGES[key]?.[index];
  if (exact) return text.replace(text.trim(), exact);
  const dayText = (day: string) =>
    [`Day ${day}`, `第${day}天`, `第${day}天`, `${day}日目`, `Tag ${day}`, `Jour ${day}`][index]!;
  const day = /^(?:(\d{4}\.\d{2}\.\d{2}) · )?(?:Day (\d+)|(\d+)일차)$/.exec(key);
  if (day) return `${day[1] ? `${day[1]} · ` : ""}${dayText(day[2] ?? day[3]!)}`;
  const routeMap = /^Day (\d+) 동선 지도$/.exec(key);
  if (routeMap)
    return [
      `Day ${routeMap[1]} route map`,
      `第${routeMap[1]}天路线地图`,
      `第${routeMap[1]}天路線地圖`,
      `${routeMap[1]}日目のルートマップ`,
      `Routenkarte für Tag ${routeMap[1]}`,
      `Carte du jour ${routeMap[1]}`,
    ][index];
  const field =
    /^(.+) (예정 시각 해제|방문 예정 시각|이전 날|다음 날|제거|위로|아래로|추가|날짜)$/.exec(key);
  if (field) {
    const actions: Record<string, ScreenTranslations> = {
      "예정 시각 해제": [
        "Clear planned time",
        "清除预定时间",
        "清除預定時間",
        "予定時刻を解除",
        "Geplante Zeit löschen",
        "Effacer l’heure prévue",
      ],
      "방문 예정 시각": [
        "Planned visit time",
        "预定参观时间",
        "預定參觀時間",
        "訪問予定時刻",
        "Geplante Besuchszeit",
        "Heure de visite prévue",
      ],
      "이전 날": ["Previous day", "前一天", "前一天", "前の日", "Vorheriger Tag", "Jour précédent"],
      "다음 날": ["Next day", "后一天", "後一天", "次の日", "Nächster Tag", "Jour suivant"],
      제거: ["Remove", "移除", "移除", "削除", "Entfernen", "Retirer"],
      위로: ["Move up", "上移", "上移", "上へ移動", "Nach oben", "Monter"],
      아래로: ["Move down", "下移", "下移", "下へ移動", "Nach unten", "Descendre"],
      추가: ["Add", "添加", "加入", "追加", "Hinzufügen", "Ajouter"],
      날짜: ["Visit date", "参观日期", "參觀日期", "訪問日", "Besuchsdatum", "Date de visite"],
    };
    return `${actions[field[2]!]![index]}: ${PLANNING_SCREEN_MESSAGES[field[1]!]?.[index] ?? field[1]}`;
  }
  const outside =
    /^(.+)에 장소가 남아 있어요\. 종료일을 늘리거나 해당 장소를 기간 안으로 옮겨 주세요\. 장소는 삭제되지 않았어요\.$/.exec(
      key,
    );
  if (outside) {
    const days = outside[1]!
      .replace(/Day (\d+)/g, (_, day: string) => dayText(day))
      .replace(
        / 외 (\d+)일$/,
        (_, count: string) =>
          [
            `, and ${count} more days`,
            `，另有${count}天`,
            `，另有${count}天`,
            `、ほか${count}日`,
            `, und ${count} weitere Tage`,
            `, et ${count} autres jours`,
          ][index]!,
      );
    return [
      `Stops remain on ${days}. Extend the end date or move these stops into the travel period. Nothing was deleted.`,
      `${days}仍有地点。请延长结束日期或将地点移入旅行期间。未删除任何地点。`,
      `${days}仍有地點。請延長結束日期或將地點移入旅行期間。未刪除任何地點。`,
      `${days}に場所が残っています。終了日を延ばすか期間内に移動してください。場所は削除されていません。`,
      `Für ${days} sind noch Stopps geplant. Verlängere die Reise oder verschiebe sie in den Reisezeitraum. Es wurde nichts gelöscht.`,
      `Des étapes restent prévues pour ${days}. Prolongez le voyage ou déplacez-les dans les dates prévues. Aucun lieu n’a été supprimé.`,
    ][index];
  }
  const stops = /^(\d+)곳$/.exec(key);
  if (stops)
    return [
      `${stops[1]} stops`,
      `${stops[1]}个地点`,
      `${stops[1]}個地點`,
      `${stops[1]}か所`,
      `${stops[1]} Stopps`,
      `${stops[1]} étapes`,
    ][index];
  const duration = /^(?:(\d+)시간\s*)?(?:(\d+)분)?$/.exec(key);
  if (duration && (duration[1] || duration[2])) {
    const h = duration[1],
      m = duration[2];
    return [
      h ? [`${h} hr`, `${h}小时`, `${h}小時`, `${h}時間`, `${h} Std.`, `${h} h`][index] : undefined,
      m
        ? [`${m} min`, `${m}分钟`, `${m}分鐘`, `${m}分`, `${m} Min.`, `${m} min`][index]
        : undefined,
    ]
      .filter(Boolean)
      .join(" ");
  }
  return undefined;
}
