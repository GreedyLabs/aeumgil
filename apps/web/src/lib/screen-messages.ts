const languages: Lang[] = ["en", "zh-CN", "zh-TW", "ja", "de", "fr"];
export function screenMessage(text: string, lang: Lang): string | undefined {
  if (lang === "ko") return undefined;
  const index = languages.indexOf(lang);
  const key = text.trim().replace(/\s+/g, " ");
  const translated = SCREEN_MESSAGES[key]?.[index];
  if (translated) return text.replace(text.trim(), translated);
  if (key.includes(" · ")) {
    const parts = key.split(" · ");
    const values = parts.map((part) => screenMessage(part, lang));
    if (values.every(Boolean)) return values.join(" · ");
  }
  const region = regions.find((region) => region.ko === key);
  if (region) return region.en;
  if (/^\d+일(?: 코스)?$/.test(key)) {
    const days = key.match(/^\d+/)![0];
    return [
      `${days} ${days === "1" ? "day" : "days"}`,
      `${days}天`,
      `${days}天`,
      `${days}日`,
      `${days} ${days === "1" ? "Tag" : "Tage"}`,
      `${days} ${days === "1" ? "jour" : "jours"}`,
    ][index];
  }
  const stay = /^(\d+)박 (\d+)일$/.exec(key);
  if (stay)
    return [
      `${stay[2]} ${stay[2] === "1" ? "day" : "days"} / ${stay[1]} ${stay[1] === "1" ? "night" : "nights"}`,
      `${stay[2]}天${stay[1]}晚`,
      `${stay[2]}天${stay[1]}晚`,
      `${stay[1]}泊${stay[2]}日`,
      `${stay[2]} ${stay[2] === "1" ? "Tag" : "Tage"} / ${stay[1]} ${stay[1] === "1" ? "Nacht" : "Nächte"}`,
      `${stay[2]} ${stay[2] === "1" ? "jour" : "jours"} / ${stay[1]} ${stay[1] === "1" ? "nuit" : "nuits"}`,
    ][index];
  return undefined;
}
