const languages: readonly Lang[] = ["en", "zh-CN", "zh-TW", "ja", "de", "fr"];
export function themeMessage(text: string, lang: Lang): string | undefined {
  if (lang === "ko") return undefined;
  const key = text.trim();
  const translated = THEME_MESSAGES[key]?.[languages.indexOf(lang)];
  return translated ? text.replace(key, translated) : undefined;
}
