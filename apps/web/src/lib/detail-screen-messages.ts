function translated(values: ScreenTranslations, lang: Exclude<Lang, "ko">): string {
  return values[LANGUAGE_INDEX[lang]]!;
}

/** 지정한 UI 문구만 변환한다. 알 수 없는 관광 설명·사용자 글은 호출자가 원문으로 유지한다. */
export function detailScreenMessage(text: string, lang: Lang): string | undefined {
  if (lang === "ko") return undefined;
  const key = text.trim().replace(/\s+/g, " ");
  const exact = DETAIL_SCREEN_MESSAGES[key];
  if (exact) return text.replace(text.trim(), translated(exact, lang));
  const congestion = /^(정체 속도|서행 속도) (\d+)구간$/.exec(key);
  if (congestion) {
    const count = congestion[2]!;
    const range = congestion[1] === "정체 속도" ? "<40" : "40–<80";
    return translated(
      [
        `${count} ${count === "1" ? "section" : "sections"} at ${range} km/h`,
        `${count}个路段 ${range} km/h`,
        `${count}個路段 ${range} km/h`,
        `${count}区間で${range} km/h`,
        `${count} ${count === "1" ? "Abschnitt" : "Abschnitte"} mit ${range} km/h`,
        `${count} ${count === "1" ? "tronçon" : "tronçons"} à ${range} km/h`,
      ],
      lang,
    );
  }
  const missing = /^(갱신 지연|미측정) (\d+)구간$/.exec(key);
  if (missing) {
    const count = missing[2]!;
    const delayed = missing[1] === "갱신 지연";
    return translated(
      [
        `${count} ${count === "1" ? "section" : "sections"}: ${delayed ? "update delayed" : "not measured"}`,
        `${delayed ? "更新延迟" : "未测量"}：${count}个路段`,
        `${delayed ? "更新延遲" : "未測量"}：${count}個路段`,
        `${delayed ? "更新遅延" : "未測定"}：${count}区間`,
        `${count} ${count === "1" ? "Abschnitt" : "Abschnitte"}: ${delayed ? "verzögert" : "nicht gemessen"}`,
        `${count} ${count === "1" ? "tronçon" : "tronçons"} : ${delayed ? "mise à jour retardée" : "non mesuré"}`,
      ],
      lang,
    );
  }
  const highway = /^고속도로 (\d+)호선$/.exec(key);
  if (highway)
    return translated(
      [
        `Expressway ${highway[1]}`,
        `${highway[1]}号高速公路`,
        `${highway[1]}號高速公路`,
        `高速道路${highway[1]}号線`,
        `Autobahn ${highway[1]}`,
        `Autoroute ${highway[1]}`,
      ],
      lang,
    );
  const counts =
    /^관측 구간 수: 40km\/h 미만 (\d+), 40 이상 80 미만 (\d+), 80 이상 (\d+), 현재 관측 없음 (\d+)$/.exec(
      key,
    );
  if (counts) {
    const [, slow, delayed, clear, unknown] = counts;
    return translated(
      [
        `Section counts: below 40 km/h ${slow}; 40 to below 80 ${delayed}; 80 or above ${clear}; no current measurement ${unknown}`,
        `路段数：低于40km/h ${slow}；40至低于80 ${delayed}；80以上 ${clear}；当前无测量 ${unknown}`,
        `路段數：低於40km/h ${slow}；40至低於80 ${delayed}；80以上 ${clear}；目前無測量 ${unknown}`,
        `区間数：40km/h未満 ${slow}、40以上80未満 ${delayed}、80以上 ${clear}、現在の測定なし ${unknown}`,
        `Abschnitte: unter 40 km/h ${slow}; 40 bis unter 80 ${delayed}; ab 80 ${clear}; ohne aktuelle Messung ${unknown}`,
        `Tronçons : moins de 40 km/h ${slow} ; de 40 à moins de 80 ${delayed} ; 80 ou plus ${clear} ; sans mesure actuelle ${unknown}`,
      ],
      lang,
    );
  }
  const hour = /^([01]?\d|2[0-3])시$/.exec(key);
  if (hour)
    return translated(
      [
        `${hour[1]!.padStart(2, "0")}:00`,
        `${hour[1]}时`,
        `${hour[1]}時`,
        `${hour[1]}時`,
        `${hour[1]!.padStart(2, "0")}:00`,
        `${hour[1]!.padStart(2, "0")}:00`,
      ],
      lang,
    );
  return undefined;
}

/** 수량을 잘린 조사와 이어 붙이지 않고 언어에 맞는 한 문장으로 만든다. */
export function formatEventProgress(visible: number, total: number, lang: Lang): string {
  if (lang === "ko") return `${total}개 중 ${visible}개 행사를 보고 있어요`;
  return translated(
    [
      `Showing ${visible} of ${total} events`,
      `显示${total}个活动中的${visible}个`,
      `顯示${total}個活動中的${visible}個`,
      `${total}件中${visible}件のイベントを表示`,
      `${visible} von ${total} Veranstaltungen angezeigt`,
      `${visible} événements affichés sur ${total}`,
    ],
    lang,
  );
}

/** 관측지의 KST로 표시한다. ICU 버전별 구분 문자 차이로 화면 복원이 실패하지 않게 직접 조합한다. */
export function formatObservationTime(value: string, lang: Lang): string {
  const time = new Date(value);
  if (!Number.isFinite(time.getTime())) return "—";
  const kst = new Date(time.getTime() + 9 * 60 * 60 * 1000);
  const month = kst.getUTCMonth() + 1;
  const day = kst.getUTCDate();
  const clock = `${String(kst.getUTCHours()).padStart(2, "0")}:${String(kst.getUTCMinutes()).padStart(2, "0")}`;
  if (lang === "ko") return `${month}. ${day}. ${clock}`;
  if (lang === "en") return `${month}/${day}, ${clock}`;
  if (lang === "de") return `${day}.${month}., ${clock}`;
  if (lang === "fr")
    return `${String(day).padStart(2, "0")}/${String(month).padStart(2, "0")} ${clock}`;
  return `${month}/${day} ${clock}`;
}
